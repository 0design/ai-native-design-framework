test('MCP serves the AINDF query surface, validates, and stages only with an author token', async () => {
  const stored = new Map();
  const staging = { authorize: token => token === 'author-1' ? 'author-1' : null, put: async (key, bytes) => { const created = !stored.has(key); if (created) stored.set(key, bytes); return { created }; } };
  const handle = createDsMcp(bundle, { staging });
  const call = async (name, args, auth) => (await handle({ jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name, arguments: args } }, { auth })).result;
  assert.equal((await handle({ jsonrpc: '2.0', id: 0, method: 'initialize', params: {} })).result.serverInfo.name, 'aindf-ds-tiny');
  const tools = (await handle({ jsonrpc: '2.0', id: 1, method: 'tools/list' })).result.tools.map(t => t.name);
  for (const t of ['list-by-facet', 'slot-accepts', 'applicable-modifiers', 'get-preset', 'get-ds', 'get-component', 'validate-screen', 'submit-screen', 'request-extension']) assert.ok(tools.includes(t), t);
  assert.deepEqual((await call('get-ds')).structuredContent.pin, bundlePin(bundle));
  assert.equal((await call('slot-accepts', { component: 'Hero', slot: 'title' })).structuredContent.cardinality, '1..1');
  assert.equal((await call('applicable-modifiers', { component: 'Cta' })).structuredContent[0].category, 'tone');
  assert.equal((await call('validate-screen', { screen: screen() })).structuredContent.ok, true);
  assert.equal((await call('validate-screen', { screen: mutate(s => { s.sections[0].props.style = 'x'; }) })).structuredContent.ok, false);
  assert.equal((await call('submit-screen', { screen: screen() })).structuredContent.code, 'UNAUTHORIZED');
  assert.equal((await call('submit-screen', { screen: screen() }, 'forged')).structuredContent.code, 'UNAUTHORIZED');
  assert.equal((await call('submit-screen', { screen: mutate(s => { s.sections[0].props.className = 'x'; }) }, 'author-1')).structuredContent.state, 'rejected');
  const ok = (await call('submit-screen', { screen: screen() }, 'author-1')).structuredContent;
  assert.equal(ok.state, 'draft');
  assert.ok([...stored.keys()].some(k => k.endsWith(`${ok.id}.screen.json`)));
  assert.equal((await call('request-extension', { need: 'a carousel' }, 'author-1')).structuredContent.state, 'requested');
  assert.equal((await createDsMcp(bundle)({ jsonrpc: '2.0', id: 1, method: 'tools/call', params: { name: 'submit-screen', arguments: { screen: screen() } } })).result.structuredContent.code, 'READ_ONLY');
  assert.throws(() => createDsMcp({ ...bundle, ds: { ...bundle.ds, version: '9.9.9' } }), /BUNDLE_INTEGRITY/);
});

