test('codegen is deterministic, emits props as JSON data only and imports only the DS module', () => {
  const bytes = Buffer.from(JSON.stringify(screen()));
  const a = generateNextPage(bundle, screen(), { screenPath: 's.json', screenBytes: bytes });
  assert.equal(a, generateNextPage(bundle, screen(), { screenPath: 's.json', screenBytes: bytes }));
  assert.match(a, /^\/\/ @generated by aindf-kit/);
  assert.deepEqual([...a.matchAll(/^import .* from (.+);$/gm)].map(m => m[1]), ['"@tiny/ds"']);
  const tricky = mutate(s => { s.sections[0].slots.title[0].props.text = '"}}/><script>x'; });
  assert.throws(() => generateNextPage(bundle, mutate(s => { s.sections[0].props.className = 'x'; }), { screenPath: 's', screenBytes: bytes }), /SCREEN_REJECTED/);
  const code = generateNextPage(bundle, { ...tricky, sections: [{ ...tricky.sections[0], slots: { ...tricky.sections[0].slots, title: [{ component: 'Heading', props: { text: '"}}/><script>' } }] } }] }, { screenPath: 's', screenBytes: bytes });
  assert.match(code, /text=\{"\\"}}\/><script>"\}/);
});

